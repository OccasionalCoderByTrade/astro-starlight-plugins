// Regenerates src/plugins/expressive-code-emphasis/fonts.ts from Google Fonts:
// Source Code Pro, weight 900, upright, latin + latin-ext subsets only.
// Run with `npm run vendor:fonts`.
import { Buffer } from "node:buffer";
import { writeFile } from "node:fs/promises";

const googleFontsCssUrl =
  "https://fonts.googleapis.com/css2?family=Source+Code+Pro:wght@900";
const vendoredSubsets = ["latin-ext", "latin"];
const outputFileUrl = new URL(
  "../src/plugins/expressive-code-emphasis/fonts.ts",
  import.meta.url,
);

// Google serves woff2 only to browsers that announce support for it.
const browserUserAgent =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const googleFontsCss = await (
  await fetch(googleFontsCssUrl, {
    headers: { "User-Agent": browserUserAgent },
  })
).text();

// Each @font-face block is preceded by a `/* <subset> */` comment.
const fontFacePattern =
  /\/\* ([\w-]+) \*\/\s*@font-face\s*\{[^}]*?src:\s*url\(([^)]+)\)[^}]*?unicode-range:\s*([^;]+);/g;
const fontFaces = [];
for (const [, subset, woff2Url, unicodeRange] of googleFontsCss.matchAll(
  fontFacePattern,
)) {
  if (!vendoredSubsets.includes(subset)) continue;
  const woff2Bytes = await (await fetch(woff2Url)).arrayBuffer();
  fontFaces.push({
    subset,
    unicodeRange: unicodeRange.trim(),
    woff2Base64: Buffer.from(woff2Bytes).toString("base64"),
  });
}

const missingSubsets = vendoredSubsets.filter(
  (subset) => !fontFaces.some((fontFace) => fontFace.subset === subset),
);
if (missingSubsets.length > 0) {
  throw new Error(`Google Fonts CSS has no ${missingSubsets.join(", ")} face`);
}

const fontsModule = `/*!
 * Source Code Pro, weight 900, upright: ${vendoredSubsets.join(" + ")} subsets.
 * Copyright 2010-2020 Adobe (http://www.adobe.com/), with Reserved Font Name
 * 'Source'. Licensed under the SIL Open Font License, Version 1.1:
 * https://openfontlicense.org
 *
 * Generated by scripts/vendor-source-code-pro.mjs from ${googleFontsCssUrl}
 * on ${new Date().toLocaleDateString("en-CA")}. Don't edit by hand.
 */

export const sourceCodeProFontFaces: {
  subset: string;
  unicodeRange: string;
  woff2Base64: string;
}[] = ${JSON.stringify(fontFaces, null, 2)};
`;

await writeFile(outputFileUrl, fontsModule);
console.log(
  `Wrote ${fontFaces.map((fontFace) => fontFace.subset).join(", ")} to ${outputFileUrl.pathname}`,
);
